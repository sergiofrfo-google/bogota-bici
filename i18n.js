const ORD_EN = ['', 'first', 'second', 'third', 'fourth', 'fifth', 'sixth'];

function L(es, vars) {
  let s = LANG === 'en' ? (EN[es] ?? es) : es;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}
// numbers: decimal comma in Spanish, point in English
const dec = (x, d = 1) => { const s = x.toFixed(d); return LANG === 'es' ? s.replace('.', ',') : s; };

// static text in index.html: data-i18n (text), data-i18n-ph (placeholder), data-i18n-aria (aria-label)
function applyStatic() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    if (!el.dataset.es) el.dataset.es = el.dataset.i18n;
    const txt = [...el.childNodes].find((n) => n.nodeType === 3 && n.textContent.trim());
    if (txt) txt.textContent = ' ' + L(el.dataset.es) + ' ';
  }
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = L(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', L(el.dataset.i18nAria));
}
